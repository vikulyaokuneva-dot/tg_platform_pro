AGRO_RELEVANCE_RX = re.compile(
    "|".join(rx for _, _, _, rx in TOPICS) +
    r"|агро|аграрн|сельск\w+ хозяйств|землепольз|фермер", re.I)

# Практическая ценность: инструкция/вывод/измеримость. Заголовок весомее тела.
PRACTICAL_RX = re.compile(
    r"\bкак\b|совет|способ|ошибк|пошагов|схем[аи]|инструкц|рекомендац|правил[ао]|"
    r"когда (сажать|сеять|копать|обрезать|укрывать|подкарм)|что делать|"
    r"подел|сделат[ья]|вырастит[ья]?|посадит[ья]?|подкормит|обрезк|укры|размножить|"
    r"выбор|сравнени|чем обработат|чем подкорм|не делат|лучш[еи]", re.I)
# Обращение к читателю повелительным наклонением («проверьте», «ориентируйтесь») —
# главный маркер «материал про действия, а не про то, что случилось». Числовой
# ньюс-текст («составляет 7 % от нормы») таких форм не содержит.
IMPERATIVE_RX = re.compile(r"\b[а-яё]{4,}(?:ите|ьте|ейте)(?:сь)?\b", re.I)
NUM_RX = re.compile(r"\d[\d.,]*\s*(%|см|мм|л|литров?|кг|грамм|г|шт|раз|минут|час|дн|недел|лет|°|C\b|п\.п\.)", re.I)

# Рекламные/коммерческие маркеры (для агро-канала — стоп, источник дохода != польза).
AD_RX = re.compile(
    r"купить|заказать|оформить заказ|промокод|скидк[аи]?\s+\d|акци[яи]\b|распродаж|"
    r"цена от|прайс-лист|доставк[аа] по росс|бесплатн\w+ (консульт|доставк|замер)|"
    r"реклама|партн[её]рский материал|на правах реклам|каталог товаров", re.I)

# Чистая новостная подача («случилось», а не «сделай/узнай»).
NEWSISH_RX = re.compile(
    r"сообща(?:ет|л[иаи]|ли)|заявил[аи]?|планирует|запустил[аи]?|подписан[аи]?|"
    r"вступил в силу|принят|законопроект|выступил|произошл|сообщил[аи]? \w+|"
    r"по данным|за период|вырос на|по итога", re.I)

# SEO-вода: нет ни одной конкретики (культуры/числа/действия) + маркеры-пустышки.
WATER_RX = re.compile(
    r"в наш[её] время|современн[а-яё]+ мир|не секрет|каждый дачник мечт|"
    r"без этого невозможно|по-настоящему|унтикальн|лучш[еи]е решения|интернет-магазин", re.I)

TOPIC_RULES = tuple((k, emoji, tag, re.compile(rx, re.I)) for k, emoji, tag, rx in TOPICS)


def detect_topics(title, text):
    """-> [(ключ, эмодзи, тег)] по заголовку (вес x2) и началу тела."""
    head = title or ""
    body = (text or "")[:3500]
    hits = []
    for key, emoji, tag, rx in TOPIC_RULES:
        score = len(rx.findall(head)) * 2 + len(rx.findall(body))
        if score:
            hits.append((score, key, emoji, tag))
    hits.sort(reverse=True)
    return [(k, e, t) for _, k, e, t in hits[:3]]


def classify(title, text, published_at=""):
    """-> dict(type, confidence, topics[(key,emoji,tag)], signals).

    type: practical | news | offtopic | ad.
    """
    title = title or ""
    text = text or ""
    head_body = title + "\n" + text[:3000]
    topics = detect_topics(title, text)
    signals = {}

    ad_hits = AD_RX.findall(title) + AD_RX.findall(text[:400])
    signals["ad"] = len(ad_hits)
    practical = len(PRACTICAL_RX.findall(title)) * 2 + len(PRACTICAL_RX.findall(text[:4000]))
    numbers = len(NUM_RX.findall(head_body))
    agro_relevant = bool(AGRO_RELEVANCE_RX.search(head_body)) and bool(topics)
    signals.update(practical=practical, numbers=numbers, topics=len(topics))

    # 1) явная коммерция — в рекламу не пускаем никогда
    if len(ad_hits) >= 2 or (ad_hits and not agro_relevant):
        return {"type": "ad", "confidence": 0.9, "topics": topics, "signals": signals}
    # 2) вне агро-повестки
    if not agro_relevant:
        return {"type": "offtopic", "confidence": 0.8, "topics": topics, "signals": signals}
    # 3) практичный материал. Решает обращение к читателю, а не обилие цифр
    #    (научная/рыночная сводка с числами — это news, не «сделай сам»):
    #    A) заголовок обещает пользу + есть конкретика в тексте;
    #    B) плотный текст инструкций (2+ повелительных обращения);
    #    C) полезный нумерованный список («8 способов…» — узнавание).
    title_pract = len(PRACTICAL_RX.findall(title))
    imper = len(IMPERATIVE_RX.findall(text[:4000]))
    newsish = len(NEWSISH_RX.findall(head_body))
    # Рубрика должна быть видна в ЗАГОЛОВКЕ (рамка пользы), а не только в теле:
    # это отличает «7 растений…», «чем белить…» от научной сводки «эрозия болот
    # переносит 380 тонн углерода» (темы лишь в тексте + «сообщает/за период»).
    title_topics = [k for k, rx in ((k, re.compile(rxl, re.I))
                                    for k, _e, _t, rxl in TOPICS) if rx.search(title)]
    signals["imperative"] = imper
    signals["newsish"] = newsish
    practical_verdict = (
        (title_pract >= 1 and (numbers >= 1 or imper >= 1 or len(topics) >= 2))
        or imper >= 2
        or (bool(re.search(r"\d+", title)) and len(title_topics) >= 1
            and len(topics) >= 1 and practical >= 1 and newsish == 0))
    if practical_verdict:
        conf = min(0.95, 0.6 + 0.05 * practical + 0.05 * imper + 0.02 * numbers)
        return {"type": "practical", "confidence": round(conf, 2), "topics": topics,
                "signals": signals}
    # 4) SEO-вода: тема есть, но ни действия, ни вывода — в корзину offtopic
    #    (объём/«тонкость» — забота process-гейта, тут только смысл)
    if WATER_RX.search(head_body) and practical <= 1:
        return {"type": "offtopic", "confidence": 0.6, "topics": topics, "signals": signals}
    # 5) новость о событии без практического вывода
    if NEWSISH_RX.search(head_body):
        return {"type": "news", "confidence": 0.7, "topics": topics, "signals": signals}
    # 6) релевантно, но вывода нет — не берём (консервативно)
    return {"type": "news", "confidence": 0.55, "topics": topics, "signals": signals}
