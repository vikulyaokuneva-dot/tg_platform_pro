    ("machinery", "🔧 Техника", "#Техника",
     r"трактор|комбайн|навесн|плуг|фрезер|культиватор|бензопил|секатор|инструмент|"
     r"оборудован|минитрактор|сеялк|опрыскивател"),
    ("economics", "📊 Экономика", "#Экономика",
     r"экономик|себестоим|рентабельн|урожайност|гектар|надой|прибыл|затрат|инвестиц|"
     r"цен[аы] на|\bрынк"),
